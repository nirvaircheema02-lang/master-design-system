#!/usr/bin/env node
import { readFileSync, writeFileSync } from "node:fs";
import YAML from "yaml";
import { dirname, join, resolve } from "node:path";
import { fileURLToPath } from "node:url";
import { chromium } from "playwright";
import { probeMany, type ProbeJob } from "./probe.ts";
import { probeUiMany, UI_KINDS, type UiJob } from "./probe-ui.ts";
import { buildInventory, coverage, loadInventory, matrixMarkdown, type SourceEntry } from "./inventory.ts";

const root = resolve(dirname(fileURLToPath(import.meta.url)), "../../..");
const [cmd, ...rest] = process.argv.slice(2);
const flag = (n: string) => { const i = rest.indexOf(`--${n}`); return i >= 0 ? rest[i + 1] : undefined; };

if (cmd === "probe") {
  const jobs = JSON.parse(readFileSync(resolve(flag("jobs") ?? join(root, "research/jobs.json")), "utf8")) as ProbeJob[];
  const only = flag("only")?.split(",");
  const sel = only ? jobs.filter((j) => only.includes(j.id)) : jobs;
  const ui = sel.filter((j) => UI_KINDS.has(j.kind ?? ""));
  const classic = sel.filter((j) => !UI_KINDS.has(j.kind ?? ""));
  const results = classic.length ? await probeMany(classic, join(root, "research/probe"), Number(flag("concurrency") ?? 4), process.env.PW_CHROMIUM || undefined) : [];
  let uiResults: Awaited<ReturnType<typeof probeUiMany>> = [];
  if (ui.length) {
    const browser = await chromium.launch(process.env.PW_CHROMIUM ? { executablePath: process.env.PW_CHROMIUM } : {});
    uiResults = await probeUiMany(ui as unknown as UiJob[], join(root, "research/probe"), browser, Number(flag("concurrency") ?? 3));
    await browser.close();
  }
  const all = [...results, ...uiResults];
  console.log(`probed ${all.length}: ${all.filter((r) => r.ok).length} ok, ${all.filter((r) => !r.ok).length} failed`);
} else if (cmd === "build") {
  const src = YAML.parse(readFileSync(join(root, "research/refs.source.yaml"), "utf8"), { merge: true }) as SourceEntry[];
  const refs = buildInventory(src, { probeDir: join(root, "research/probe"), outDir: join(root, "research/inventory"), today: flag("date") ?? new Date().toISOString().slice(0, 10) });
  console.log(`built ${refs.length} REF records`);
} else if (cmd === "validate" || cmd === "matrix") {
  const inv = loadInventory(join(root, "research/inventory"));
  for (const e of inv.errors) console.error("ERROR " + e);
  if (cmd === "matrix") {
    writeFileSync(join(root, "research/MATRIX.md"), `# Comparison matrix\n\nGenerated by \`master-research matrix\`. Scores 1–5; overall is weighted (see packages/research/src/schema.ts).\n\n${matrixMarkdown(inv.refs)}\n`);
    writeFileSync(join(root, "research/COVERAGE.json"), JSON.stringify(coverage(inv.refs), null, 2));
  }
  console.log(JSON.stringify(coverage(inv.refs)));
  process.exit(inv.errors.length ? 1 : 0);
} else {
  console.error("usage: master-research probe|build|validate|matrix [--jobs file] [--only id,id] [--concurrency n]");
  process.exit(2);
}
