import { existsSync } from "node:fs";
import { dirname, join } from "node:path";
import { readText, sha256 } from "./util.ts";

/** Library each adapter module wraps; becomes a dependency of the generated site. */
export const HEADLESS_LIBS: Record<string, string> = {
  tabs: "@radix-ui/react-tabs", dialog: "@radix-ui/react-dialog", menu: "@radix-ui/react-dropdown-menu", accordion: "@radix-ui/react-accordion", popover: "@radix-ui/react-popover", tooltip: "@radix-ui/react-tooltip",
};

export interface HeadlessCopy { files: Record<string, string>; deps: Record<string, string>; hash: string }

/** Read the adapter modules a site needs (plus the local modules they import) from the Master's headless package. */
export function resolveHeadless(srcRoot: string, modules: string[]): HeadlessCopy | { error: string } {
  const files: Record<string, string> = {};
  const add = (file: string): string | undefined => {
    if (file in files) return undefined;
    const p = join(srcRoot, file);
    if (!existsSync(p)) return `headless source ${file} not found under ${srcRoot}`;
    const src = readText(p);
    files[file] = src;
    for (const m of src.matchAll(/from\s+"\.\/([a-z]+\.tsx)"/g)) { const e = add(m[1]!); if (e) return e; }
    return undefined;
  };
  for (const m of [...modules].sort()) { if (!HEADLESS_LIBS[m]) return { error: `unknown headless module '${m}'` }; const e = add(`${m}.tsx`); if (e) return { error: e }; }
  files["index.ts"] = `/* Generated by master-generator: the adapter modules this site uses. */\n${[...modules].sort().map((m) => `export * from "./${m}.tsx";`).join("\n")}\n`;
  const pkgPath = join(dirname(srcRoot), "package.json");
  const pkgDeps: Record<string, string> = existsSync(pkgPath) ? JSON.parse(readText(pkgPath)).dependencies ?? {} : {};
  const deps: Record<string, string> = {};
  for (const m of modules) deps[HEADLESS_LIBS[m]!] = pkgDeps[HEADLESS_LIBS[m]!] ?? "latest";
  for (const k of ["react", "react-dom"]) deps[k] = pkgDeps[k] ?? "latest";
  files["package.json"] = JSON.stringify({ name: "@master-ds/headless", version: "0.0.0", private: true, type: "module", exports: { ".": "./index.ts" }, dependencies: deps }, null, 2) + "\n";
  const hash = sha256(Object.entries(files).sort(([a], [b]) => a.localeCompare(b)).map(([p, c]) => p + "\0" + c).join("\n"));
  return { files, deps, hash };
}
